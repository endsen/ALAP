"""Build shared OpenAPI components from the canonical JSON Schemas."""

import argparse
import copy
import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
COMPONENTS = {
    "stable_condition": "StableCondition",
    "plan_task": "PlanTask",
    "plan_proposal": "PlanProposalRecord",
    "plan_revision": "PlanRevision",
    "dataset_manifest": "DatasetManifestRecord",
    "agent_manifest": "AgentManifest",
    "capability": "CapabilityManifest",
    "command": "CommandEnvelope",
    "event": "DomainEvent",
}


def convert(value):
    if isinstance(value, list):
        return [convert(item) for item in value]
    if not isinstance(value, dict):
        return value
    result = {}
    for key, item in value.items():
        if key in {"$id", "$schema"}:
            continue
        if key == "$ref":
            name = item.removesuffix(".schema.json")
            result[key] = f"#/components/schemas/{COMPONENTS[name]}"
        else:
            result[key] = convert(item)
    return result


def build() -> str:
    api = yaml.safe_load((ROOT / "contracts/openapi.base.yaml").read_text(encoding="utf-8"))
    schemas = api["components"]["schemas"]
    for name, component in COMPONENTS.items():
        schemas[component] = convert(
            json.loads((ROOT / f"contracts/{name}.schema.json").read_text(encoding="utf-8"))
        )
    # Server-owned IDs and agent identity come from the authenticated context.
    request = copy.deepcopy(schemas["PlanProposalRecord"])
    for field in ("proposal_id", "experiment_id", "source_agent_run_id"):
        request["properties"].pop(field)
        request["required"].remove(field)
    request["title"] = "PlanProposalCreate"
    schemas["PlanProposalCreate"] = request
    response = copy.deepcopy(schemas["PlanProposalRecord"])
    response["properties"].update(
        plan_revision_id={"type": "string", "minLength": 1},
        plan_hash={"type": "string", "pattern": "^[a-f0-9]{64}$"},
        state={"enum": ["PROPOSED", "VALIDATED", "REJECTED", "AWAITING_APPROVAL"]},
    )
    response["required"].append("state")
    response["allOf"] = [
        {
            "if": {"properties": {"state": {"enum": ["VALIDATED", "AWAITING_APPROVAL"]}}},
            "then": {"required": ["plan_revision_id", "plan_hash"]},
        }
    ]
    schemas["PlanProposal"] = response
    public_dataset = copy.deepcopy(schemas["DatasetManifestRecord"])
    public_dataset["properties"]["status"] = {"const": "COMMITTED"}
    schemas["DatasetManifest"] = public_dataset
    return "# Generated by scripts/build_openapi.py; edit base + JSON Schemas.\n" + yaml.safe_dump(
        api, sort_keys=False, allow_unicode=True
    )


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / "contracts/openapi.yaml"
    output = build()
    if args.check:
        if not target.exists() or target.read_text(encoding="utf-8") != output:
            raise SystemExit("OpenAPI drift: run python scripts/build_openapi.py")
        print("PASS: generated OpenAPI is current")
    else:
        target.write_text(output, encoding="utf-8")


if __name__ == "__main__":
    main()
