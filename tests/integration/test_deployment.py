def test_runtime_engine_dag_dataset_and_outbox(worker, execution):  # noqa: F811
    dsn = execution[4][3]
    for _ in range(6):
        assert worker.tick()["problems"] == []
    assert rows(dsn, "SELECT state FROM runs")[0]["state"] == "SUCCEEDED"
    assert rows(dsn, "SELECT state FROM datasets")[0]["state"] == "COMMITTED"
    assert len(rows(dsn, "SELECT * FROM command_ledger WHERE state='SUCCEEDED'")) == 3
    with psycopg.connect(dsn) as db:
        db.execute("INSERT INTO principals VALUES ('events','alap-events','events','service',NULL)")
    sent = []

    class Publisher:
        async def publish(self, value):
            sent.append(value)

    service = EventService(execution[0].base)
    count = asyncio.run(service.publish_once("events", Publisher()))
    assert count == len(sent) > 0
    assert rows(dsn, "SELECT count(*) n FROM outbox_events WHERE published_at IS NULL")[0]["n"] == 0


def test_runtime_agent_and_api_permissions(api, agents):  # noqa: F811
    runtime, _, model, _, _, dsn = agents
    assert get(api, "/me").status_code == 200
    with psycopg.connect(dsn) as db:
        db.execute("INSERT INTO principals VALUES ('worker','alap-agents','worker','service',NULL)")
    run = start(agents)
    model.outputs = ["offline completion"]
    report = AgentWorker(runtime, "worker", ["EXP-SIM-001"]).tick()
    assert report["runs"][0]["status"] == "COMPLETED"
    assert get(api, f"/agent-runs/{run['id']}").status_code == 200
    assert get(api, f"/agent-runs/{run['id']}", "outsider").status_code == 403
    with psycopg.connect(dsn) as db:
        with pytest.raises(psycopg.errors.CheckViolation):
            db.execute("DELETE FROM agent_trace WHERE run_id=%s", (run["id"],))


def test_existing_output_is_never_overwritten(deployment):
    directory, manifest, admin = deployment
    before = (directory / "runtime.dsn").read_bytes()
    with pytest.raises(FileExistsError):
        initialize(admin, manifest["database"] + "x", directory)
    assert (directory / "runtime.dsn").read_bytes() == before
    with psycopg.connect(admin) as db:
        assert (
            db.execute(
                "SELECT 1 FROM pg_roles WHERE rolname=%s", (manifest["database"] + "x_runtime",)
            ).fetchone()
            is None
        )


def test_incomplete_or_mismatched_deployment_refuses_migration(deployment):
    directory, manifest, _ = deployment
    marker = directory / "initialized"
    marker.unlink()
    with pytest.raises(ValueError, match="Incomplete"):
        migrate(directory)
    marker.write_text("test")
    document = directory / "deployment.json"
    document.write_text(json.dumps(manifest | {"owner": "someone_else"}))
    with pytest.raises(ValueError, match="Unexpected"):
        migrate(directory)
    document.write_text(json.dumps(manifest))
    (directory / "migration.dsn").write_text((directory / "runtime.dsn").read_text())
    with pytest.raises(ValueError, match="does not match"):
        migrate(directory)


def test_migration_cli_and_error_redaction(deployment):
    directory, _, _ = deployment
    completed = subprocess.run(
        [
            sys.executable,
            "-m",
            "alap.adapters.postgres.deployment",
            "migrate",
            "--directory",
            str(directory),
        ],
        capture_output=True,
        text=True,
        timeout=30,
    )
    assert completed.returncode == 0
    assert json.loads(completed.stdout)["event"] == "database_migrate_completed"
    env = {**os.environ, "ALAP_DATABASE_URL": "password=redaction-sentinel dbname=invalid"}
    env.pop("ALAP_DATABASE_URL_FILE", None)
    rejected = subprocess.run(
        [
            sys.executable,
            "-m",
            "alap.adapters.postgres.deployment",
            "init",
            "--name",
            "bad-name",
            "--output",
            str(directory / "unused"),
        ],
        env=env,
        capture_output=True,
        text=True,
        timeout=10,
    )
    assert rejected.returncode == 1
    assert "redaction-sentinel" not in rejected.stdout + rejected.stderr
    assert json.loads(rejected.stderr)["code"] == "DEPLOYMENT_ERROR"


def test_new_function_is_private_until_explicit_migration_grant(deployment, database):
    directory, _, _ = deployment
    with psycopg.connect((directory / "migration.dsn").read_text()) as owner:
        owner.execute(
            "CREATE FUNCTION alap.new_migration_function() RETURNS int LANGUAGE sql AS 'SELECT 1'"
        )
    with psycopg.connect(database[0]) as runtime:
        with pytest.raises(psycopg.errors.InsufficientPrivilege):
            runtime.execute("SELECT alap.new_migration_function()")
    migrate(directory)
    with psycopg.connect(database[0]) as runtime:
        assert runtime.execute("SELECT alap.new_migration_function()").fetchone() == (1,)
