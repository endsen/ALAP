@pytest.fixture
def deployment(tmp_path):
    admin = os.environ.get("ALAP_TEST_DATABASE_URL")
    if not admin or not conninfo_to_dict(admin).get("dbname", "").startswith("alap_test"):
        pytest.fail("Explicit isolated PostgreSQL admin database required")
    name = "alap_testdeploy_" + uuid4().hex[:16]
    directory = tmp_path / "private"
    try:
        manifest = initialize(admin, name, directory)
        migrate(directory)
        yield directory, manifest, admin
    finally:
        # Only the unique names generated by this fixture may be destroyed.
        with psycopg.connect(admin, autocommit=True) as db:
            db.execute(
                sql.SQL("DROP DATABASE IF EXISTS {} WITH (FORCE)").format(sql.Identifier(name))
            )
            for role in (name + "_runtime", name + "_migrator"):
                db.execute(sql.SQL("DROP ROLE IF EXISTS {}").format(sql.Identifier(role)))


@pytest.fixture
def database(deployment):
    return (deployment[0] / "runtime.dsn").read_text().strip(), None


def test_private_files_identity_and_repeat_initialization(deployment, tmp_path):
    directory, manifest, admin = deployment
    assert stat.S_IMODE(directory.stat().st_mode) == 0o700
    for file in directory.iterdir():
        assert stat.S_IMODE(file.stat().st_mode) == 0o600
    with psycopg.connect(admin) as db:
        roles = db.execute(
            "SELECT rolname,rolsuper,rolcreatedb,rolcreaterole,"
            "rolreplication,rolbypassrls,rolpassword "
            "FROM pg_authid WHERE rolname=ANY(%s)",
            ([manifest["owner"], manifest["runtime"]],),
        ).fetchall()
        assert len(roles) == 2
        assert all(not any(row[1:6]) and row[6].startswith("SCRAM-SHA-256$") for row in roles)
    with pytest.raises(ValueError, match="already exists"):
        initialize(admin, manifest["database"], tmp_path / "refused")
    assert not (tmp_path / "refused").exists()
    assert json.loads((directory / "deployment.json").read_text()) == manifest


def test_migration_repeat_ownership_and_version_protection(deployment, database):
    directory, manifest, _ = deployment
    migrate(directory)
    with psycopg.connect(database[0]) as db:
        assert db.execute("SELECT current_user,current_schema()").fetchone() == (
            manifest["runtime"],
            "alap",
        )
        owners = db.execute(
            "SELECT DISTINCT tableowner FROM pg_tables WHERE schemaname='alap'"
        ).fetchall()
        assert owners == [(manifest["owner"],)]
        assert db.execute("SELECT count(*) FROM alembic_version").fetchone()[0] == 1
        assert not db.execute(
            "SELECT pg_has_role(current_user,%s,'MEMBER')", (manifest["owner"],)
        ).fetchone()[0]
        assert not db.execute("SELECT has_schema_privilege('public','CREATE')").fetchone()[0]
        assert not db.execute(
            "SELECT has_database_privilege(current_database(),'TEMP')"
        ).fetchone()[0]


@pytest.mark.parametrize(
    "statement",
    [
        "CREATE TABLE forbidden(id int)",
        "CREATE TEMP TABLE forbidden(id int)",
        "CREATE SCHEMA forbidden",
        "ALTER TABLE principals DISABLE TRIGGER ALL",
        "DROP TABLE api_audit",
        "TRUNCATE agent_trace",
        "DELETE FROM alembic_version",
        "SET session_replication_role=replica",
        "CREATE ROLE forbidden_privilege_escalation SUPERUSER",
    ],
)
def test_runtime_cannot_change_schema_or_bypass_audit(database, statement):
    with psycopg.connect(database[0]) as db:
        with pytest.raises(psycopg.errors.InsufficientPrivilege):
            db.execute(statement)


