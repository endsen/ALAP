"""Identity, management persistence and credential ports used by the application facade."""

from typing import Protocol

from alap.application.resource_ports import ResourceStore


class CredentialManager(Protocol):
    def resolve(self, reference: str) -> str: ...
    def put(self, ref: str, value: str, expected: int) -> dict: ...
    def disable(self, ref: str, expected: int) -> dict: ...
    def list(self) -> list[dict]: ...


class APIStore(ResourceStore, Protocol):
    def principal_page(self, cursor, limit) -> dict: ...
    def change_role(self, actor, recipient, role, expected_role) -> dict: ...
    def identity(self, actor) -> dict: ...
    def runnable_agents(self, actor, experiment) -> list[dict]: ...
    def authenticate(self, token: str) -> dict: ...
    def role(self, actor, allowed) -> None: ...
    def audit(self, actor, operation, target) -> None: ...
    def request_claim(self, actor, operation, key, fingerprint) -> dict | None: ...
    def request_finish(self, actor, operation, key, result=None, error=None) -> None: ...
    def experiments(self, actor, cursor, limit) -> list[dict]: ...
    def membership_update(self, actor, experiment, recipient, role, scope, expected, revoked): ...
    def set_experiment_scope(self, actor, experiment, scope, expected) -> dict: ...
    def registry_list(self, kind, cursor, limit) -> list[dict]: ...
    def config_put(self, kind, ref, document) -> dict: ...
    def configs(self, kind) -> list[dict]: ...
    def config_disable(self, kind, ref, expected) -> dict: ...
    def visible_instruments(self, actor) -> list[dict]: ...
    def run_summary(self, actor, identity) -> dict: ...
    def run_rows(self, actor, experiment, cursor, limit) -> list[dict]: ...
    def traces(self, actor, identity) -> list[dict]: ...
    def proposals(self, actor, identity) -> list[dict]: ...
    def create_sample(self, actor, body) -> dict: ...
    def samples(self, actor) -> list[dict]: ...
    def check_source_owner(self, actor, identity) -> None: ...
    def mcp_directory(self) -> dict: ...
    def metrics(self, actor, experiment) -> dict: ...
    def audit_rows(self, after, limit) -> list[dict]: ...
    def disable_principal(self, actor) -> dict: ...
    def revoke_tokens(self, actor) -> dict: ...
    def disable_mcp(self, ref) -> dict: ...
    def disable_source(self, actor, identity) -> dict: ...
