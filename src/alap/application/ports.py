"""Persistence boundary. Actor IDs enter only from an authenticated trusted caller."""

from collections.abc import Callable
from contextlib import AbstractContextManager
from datetime import datetime
from typing import Protocol


class Repository(Protocol):
    def find(self, table: str, filters: dict, *, lock: bool = False) -> list[dict]: ...
    def generation(self, *, exclusive: bool = False) -> dict: ...
    def claim(self, resource: str) -> dict | None: ...
    def add_claim(self, lease: dict) -> None: ...
    def remove_claim(self, lease: dict) -> None: ...
    def dependency(self, run: str, task: str, parent: str) -> None: ...
    def now(self) -> datetime: ...
    def get(self, table: str, identity: str, *, lock: bool = False) -> dict: ...
    def insert(self, table: str, values: dict) -> None: ...
    def update(self, table: str, identity: str, values: dict) -> None: ...
    def add_owner(self, experiment: str, actor: str) -> None: ...
    def membership(self, experiment: str, actor: str) -> dict | None: ...
    def plans(self, experiment: str) -> list[dict]: ...
    def approvals(self, experiment: str) -> list[dict]: ...
    def runs(self, experiment: str) -> list[dict]: ...
    def events(self, experiment: str) -> list[dict]: ...
    def claim_request(
        self, actor: str, operation: str, scope: str, key: str, request_hash: str
    ) -> dict | None: ...
    def complete_request(
        self, actor: str, operation: str, scope: str, key: str, response: dict
    ) -> None: ...


Transaction = Callable[[], AbstractContextManager[Repository]]


class Authenticator(Protocol):
    def seal(self, payload: dict) -> dict: ...
    def open(self, message: dict) -> dict: ...


class GatewayPort(Protocol):
    def accept(self, signed: dict) -> dict: ...
    def query(self, command_id: str) -> dict: ...
    def recover_command(self, signed: dict) -> dict: ...
    def telemetry(self, condition: dict) -> dict: ...
    def challenge(self) -> dict: ...
    def bind_epoch(self, signed: dict) -> dict: ...
