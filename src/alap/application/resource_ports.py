"""MCP and scoped resource boundaries for the Agent application layer."""

from typing import Protocol

from alap.application.agent_ports import AgentStore


class MCPTransport(Protocol):
    def initialize(self) -> None: ...
    def list_tools(self) -> list[dict]: ...
    def call_tool(self, name: str, arguments: dict) -> dict: ...


class DatasetReader(Protocol):
    def read(self, actor: str, dataset_id: str) -> tuple[dict, bytes]: ...


class ResourceStore(AgentStore, Protocol):
    def add_source(self, actor, experiment_id, document) -> str: ...
    def share_source(self, actor, identity, recipient, *, revoked=False) -> None: ...
    def source(self, actor, experiment_id, identity, resources, agent_ref) -> dict: ...
    def search(self, actor, experiment_id, query, resources, agent_ref, limit) -> list[dict]: ...
    def register_connection(self, ref, config) -> None: ...
    def connection(self, ref) -> dict: ...
    def discovered(self, ref, tools) -> list[str]: ...
    def tool(self, identity) -> dict: ...
    def grant_tool(self, identity, actor, experiment_id, resources, reviewer, *, revoked=False): ...
    def check_refs(self, run, refs) -> None: ...
    def claim_call(self, run, call_id, tool, arguments) -> dict | None: ...
    def finish_call(self, run, call_id, result) -> None: ...
    def dataset(self, actor, experiment_id, identity, resources) -> dict: ...
    def save_analysis(self, actor, experiment_id, dataset, resources, result) -> dict: ...
    def materialize(self, run, refs) -> list[dict]: ...
    def dataset_event(self, actor, event_id, resources) -> dict: ...
    def claim_collaboration(
        self, actor, experiment, definition, evidence_hash, max_runs, cooldown
    ): ...
    def bind_collaboration(self, actor, experiment, definition, evidence_hash, identity): ...
    def has_run(self, identity) -> bool: ...
